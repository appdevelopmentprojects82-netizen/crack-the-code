/* ==========================================================================
   CODE QUEST - SOUNDS + MUSIC
   --------------------------------------------------------------------------
   The game has BUILT-IN sounds, generated by the browser - no files needed:
     - horror-style music (creepy broken music box, deep drone, swelling
       string clusters, ghostly breaths and wails, heartbeat that speeds
       up), looping for the whole game
     - keypad key beep, correct chime, wrong buzz, hint sparkle, win fanfare

   OPTIONAL: to use your own sound instead of a built-in one, put an mp3 in
   the  sounds/  folder with one of these exact names. Any file that exists
   replaces the matching built-in sound automatically:
     correct.mp3  wrong.mp3  win.mp3  hint.mp3  click.mp3  mysterious.mp3

   There is NO start-game gate: music starts on load. If the browser blocks
   sound until you interact, it starts on your first click / key press.
   Host controls: Host Panel (press T) or press  M  to switch music on / off.
   ========================================================================== */

// ---------------- SETTINGS (easy to change) ----------------
const SOUND_FOLDER      = 'sounds/';
const MUSIC_FILE        = 'mysterious.mp3';
const MUSIC_VOLUME      = 0.18;  // 0.18 = 18% (default, the slider can change it)
const MUSIC_DUCK_VOLUME = 0.10;  // music volume while the winner sound plays
const SFX_VOLUME        = 1.0;   // gift sound effects volume (0 - 1)
const MUSIC_BPM         = 60;    // tempo of the built-in music (slow = more dread)
// -----------------------------------------------------------

const Sounds = (function () {
  // ======================= optional mp3 files =============================
  const sfxNames = ['correct', 'wrong', 'win', 'hint', 'click'];
  const sfxFile = {};      // name -> Audio element
  const fileReady = {};    // name -> true once the mp3 has really loaded
  sfxNames.forEach(function (name) {
    const a = new Audio();
    a.preload = 'auto';
    a.addEventListener('canplaythrough', function () { fileReady[name] = true; });
    a.addEventListener('error', function () { fileReady[name] = false; });
    a.src = SOUND_FOLDER + name + '.mp3';
    sfxFile[name] = a;
  });

  const musicFile = new Audio();
  musicFile.loop = true;
  musicFile.preload = 'auto';
  let musicFileReady = false;

  // ======================= state ==========================================
  let musicOn = true;           // what the host wants
  let sfxOn = true;             // sound effects (Settings > Sound)
  let volume = MUSIC_VOLUME;    // slider value (0 - 1)
  let ducked = false;
  let duckTimer = null;

  try {
    const savedVol = localStorage.getItem('ctc-music-volume');
    if (savedVol !== null && !isNaN(parseFloat(savedVol))) volume = parseFloat(savedVol);
    if (localStorage.getItem('ctc-music-on') === '0') musicOn = false;
    if (localStorage.getItem('ctc-sfx-on') === '0') sfxOn = false;
  } catch (e) { /* storage not available - use defaults */ }

  // ======================= built-in synthesizer ===========================
  let ctx = null, sfxBus = null, musicBus = null;
  let beatTimer = null, nextStepTime = 0, stepIndex = 0, padFilter = null, musicIn = null, stringFilter = null, noiseBuffer = null;

  function audio() {
    if (ctx) return ctx;
    const AC = window.AudioContext || window.webkitAudioContext;
    if (!AC) return null;
    ctx = new AC();
    sfxBus = ctx.createGain();
    sfxBus.gain.value = 0.5 * SFX_VOLUME;
    sfxBus.connect(ctx.destination);
    musicBus = ctx.createGain();
    musicBus.gain.value = 0;
    musicBus.connect(ctx.destination);
    return ctx;
  }

  // one note: oscillator with a quick attack and a smooth fade-out
  function note(dest, type, freq, start, dur, gain, freqEnd) {
    const o = ctx.createOscillator();
    const g = ctx.createGain();
    o.type = type;
    o.frequency.setValueAtTime(freq, start);
    if (freqEnd) o.frequency.exponentialRampToValueAtTime(freqEnd, start + dur);
    g.gain.setValueAtTime(0.0001, start);
    g.gain.exponentialRampToValueAtTime(gain, start + 0.008);
    g.gain.exponentialRampToValueAtTime(0.0001, start + dur);
    o.connect(g); g.connect(dest);
    o.start(start);
    o.stop(start + dur + 0.05);
  }

  // ---- built-in sound effects ----
  const synthSfx = {
    // keypad key press: short electronic beep
    click: function (t) {
      note(sfxBus, 'square', 1250, t, 0.06, 0.22);
    },
    // right digit: key beep, then a bright rising two-note chime
    correct: function (t) {
      note(sfxBus, 'square', 1250, t, 0.06, 0.2);
      note(sfxBus, 'triangle', 880, t + 0.09, 0.22, 0.5);
      note(sfxBus, 'triangle', 1318.5, t + 0.2, 0.45, 0.5);
      note(sfxBus, 'sine', 2637, t + 0.2, 0.35, 0.15);
    },
    // wrong digit: key beep, then a low "access denied" double buzz
    wrong: function (t) {
      note(sfxBus, 'square', 1250, t, 0.06, 0.2);
      note(sfxBus, 'sawtooth', 150, t + 0.09, 0.16, 0.4, 110);
      note(sfxBus, 'sawtooth', 120, t + 0.29, 0.3, 0.4, 80);
    },
    // hint: quick sparkling run upwards
    hint: function (t) {
      [1046.5, 1318.5, 1568, 2093, 2637].forEach(function (f, i) {
        note(sfxBus, 'sine', f, t + i * 0.07, 0.3, 0.35);
      });
    },
    // code cracked: lock "clunk" + victory fanfare ending on a big chord
    win: function (t) {
      note(sfxBus, 'sine', 180, t, 0.3, 0.8, 50);
      const run = [523.25, 659.25, 783.99, 1046.5];
      run.forEach(function (f, i) {
        note(sfxBus, 'triangle', f, t + 0.15 + i * 0.13, 0.3, 0.45);
        note(sfxBus, 'square', f, t + 0.15 + i * 0.13, 0.2, 0.08);
      });
      [523.25, 659.25, 783.99, 1046.5, 1318.5].forEach(function (f) {
        note(sfxBus, 'triangle', f, t + 0.7, 1.8, 0.3);
      });
      [2093, 2637, 3136, 2637, 2093, 3136].forEach(function (f, i) {
        note(sfxBus, 'sine', f, t + 0.8 + i * 0.11, 0.25, 0.12);
      });
    }
  };

  // ---- built-in HORROR music ---------------------------------------------
  // A horror-film score, about one minute long, then it repeats:
  //   bars 1-4    a broken music box plays a creepy tune over a deep drone
  //   bars 5-8    the tune echoes lower; strings swell into a harsh cluster
  //   bars 9-12   the tune returns with a "wrong" note; something breathes
  //   bars 13-16  the heartbeat doubles, the music box panics, strings and
  //               a high screech rise ... then sudden silence and one low hit
  // Everything plays inside a huge echoing hall. 4 beats per bar.

  // note name -> frequency, e.g. hz('A4') = 440
  function hz(name) {
    const semis = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
    const m = /^([A-G])(#?)(\d)$/.exec(name);
    const midi = 12 * (parseInt(m[3], 10) + 1) + semis[m[1]] + (m[2] ? 1 : 0);
    return 440 * Math.pow(2, (midi - 69) / 12);
  }

  // Music-box tune: for each of the 16 bars a list of [step, note].
  // (8 steps per bar; neighbouring notes like A / A# and D / D# are what
  // make it sound "wrong" and creepy.)
  const MUSIC_BOX = [
    [[0, 'A5'], [2, 'A#5'], [4, 'A5'], [6, 'F5']],
    [[0, 'E5']],
    [[0, 'D5'], [2, 'D#5'], [4, 'D5']],
    [[2, 'C#5']],
    [[0, 'A4'], [4, 'A#4']],
    [[0, 'A4']],
    [],
    [],
    [[0, 'A5'], [2, 'A#5'], [4, 'A5'], [6, 'G#5']],
    [[0, 'E5'], [6, 'F5']],
    [[0, 'D5'], [2, 'D#5'], [4, 'D5']],
    [[2, 'C#5']],
    [[0, 'D6'], [4, 'C#6']],
    [[0, 'D6'], [2, 'C#6'], [4, 'D6'], [6, 'C#6']],
    [[0, 'D6'], [1, 'C#6'], [2, 'D6'], [3, 'C#6'], [4, 'D6'], [5, 'C#6'], [6, 'D6'], [7, 'C#6']],
    []
  ];

  // Everything goes through "musicIn": straight to the output AND through a
  // very long echo (reverb) - the empty-cathedral sound of horror films.
  function buildMusicGraph() {
    if (musicIn) return;
    musicIn = ctx.createGain();
    musicIn.connect(musicBus);

    const seconds = 5;
    const len = Math.floor(ctx.sampleRate * seconds);
    const impulse = ctx.createBuffer(2, len, ctx.sampleRate);
    for (let ch = 0; ch < 2; ch++) {
      const data = impulse.getChannelData(ch);
      for (let i = 0; i < len; i++) {
        data[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / len, 2.4);
      }
    }
    const hall = ctx.createConvolver();
    hall.buffer = impulse;
    const wet = ctx.createGain();
    wet.gain.value = 0.65;
    musicIn.connect(hall); hall.connect(wet); wet.connect(musicBus);

    padFilter = ctx.createBiquadFilter();        // dark, muffled drone
    padFilter.type = 'lowpass';
    padFilter.frequency.value = 700;
    padFilter.connect(musicIn);

    stringFilter = ctx.createBiquadFilter();     // takes the buzz off the strings
    stringFilter.type = 'lowpass';
    stringFilter.frequency.value = 1500;
    stringFilter.connect(musicIn);

    // 2 seconds of hiss, used for the "breath" sounds
    noiseBuffer = ctx.createBuffer(1, ctx.sampleRate * 2, ctx.sampleRate);
    const nd = noiseBuffer.getChannelData(0);
    for (let i = 0; i < nd.length; i++) nd[i] = Math.random() * 2 - 1;
  }

  // deep drone note: slow fade in, hold, slow fade out
  function drone(freq, start, dur, gain, type) {
    [-6, 6].forEach(function (detune) {
      const o = ctx.createOscillator();
      const g = ctx.createGain();
      o.type = type;
      o.frequency.value = freq;
      o.detune.value = detune;
      g.gain.setValueAtTime(0.0001, start);
      g.gain.linearRampToValueAtTime(gain, start + 1.5);
      g.gain.setValueAtTime(gain, start + dur - 0.5);
      g.gain.linearRampToValueAtTime(0.0001, start + dur + 1.5);
      o.connect(g); g.connect(padFilter);
      o.start(start);
      o.stop(start + dur + 1.6);
    });
  }

  // broken music box: a clear ping, slightly out of tune, with a warble
  function musicBox(freq, t, gain) {
    const f = freq * 0.992;                        // a little flat = unsettling
    note(musicIn, 'sine', f, t, 2.6, gain);
    note(musicIn, 'sine', f * 1.006, t, 2.0, gain * 0.5);   // warble
    note(musicIn, 'sine', f * 2, t, 1.0, gain * 0.25);
    note(musicIn, 'sine', f * 5.4, t, 0.25, gain * 0.06);
  }

  // strings that start from nothing, grow for "dur" seconds, then cut off
  function stringSwell(notes, t, dur, peak) {
    notes.forEach(function (n, idx) {
      const o = ctx.createOscillator();
      const g = ctx.createGain();
      const vib = ctx.createOscillator();
      const vibAmt = ctx.createGain();
      o.type = 'sawtooth';
      o.frequency.value = hz(n);
      vib.frequency.value = 5 + idx * 0.7;         // nervous tremble
      vibAmt.gain.value = hz(n) * 0.006;
      vib.connect(vibAmt); vibAmt.connect(o.frequency);
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(peak, t + dur);
      g.gain.exponentialRampToValueAtTime(0.0001, t + dur + 0.35);
      o.connect(g); g.connect(stringFilter);
      o.start(t); vib.start(t);
      o.stop(t + dur + 0.5); vib.stop(t + dur + 0.5);
    });
  }

  // very high, trembling screech (like violins played at the top)
  function screech(t, dur) {
    ['B6', 'C7', 'F7'].forEach(function (n) {
      const o = ctx.createOscillator();
      const g = ctx.createGain();
      const trem = ctx.createOscillator();
      const tremAmt = ctx.createGain();
      o.type = 'triangle';
      o.frequency.value = hz(n);
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(0.03, t + dur);
      g.gain.exponentialRampToValueAtTime(0.0001, t + dur + 0.3);
      trem.frequency.value = 11;                   // fast shiver
      tremAmt.gain.value = 0.012;
      trem.connect(tremAmt); tremAmt.connect(g.gain);
      o.connect(g); g.connect(musicIn);
      o.start(t); trem.start(t);
      o.stop(t + dur + 0.4); trem.stop(t + dur + 0.4);
    });
  }

  // a long breath / gust of cold air moving through the hall
  function breath(t, dur) {
    const src = ctx.createBufferSource();
    const band = ctx.createBiquadFilter();
    const g = ctx.createGain();
    src.buffer = noiseBuffer;
    src.loop = true;
    band.type = 'bandpass';
    band.Q.value = 2.5;
    band.frequency.setValueAtTime(350, t);
    band.frequency.linearRampToValueAtTime(900, t + dur * 0.5);
    band.frequency.linearRampToValueAtTime(300, t + dur);
    g.gain.setValueAtTime(0.0001, t);
    g.gain.linearRampToValueAtTime(0.09, t + dur * 0.5);
    g.gain.linearRampToValueAtTime(0.0001, t + dur);
    src.connect(band); band.connect(g); g.connect(musicIn);
    src.start(t);
    src.stop(t + dur + 0.1);
  }

  // distant ghost voice: slides slowly DOWN, trembling
  function wail(t, from, to) {
    const o = ctx.createOscillator();
    const g = ctx.createGain();
    const vib = ctx.createOscillator();
    const vibAmt = ctx.createGain();
    o.type = 'sine';
    o.frequency.setValueAtTime(hz(from), t);
    o.frequency.linearRampToValueAtTime(hz(to), t + 4.5);
    vib.frequency.value = 5.5; vibAmt.gain.value = 9;
    vib.connect(vibAmt); vibAmt.connect(o.frequency);
    g.gain.setValueAtTime(0.0001, t);
    g.gain.linearRampToValueAtTime(0.06, t + 1.5);
    g.gain.linearRampToValueAtTime(0.0001, t + 5);
    o.connect(g); g.connect(musicIn);
    o.start(t); vib.start(t);
    o.stop(t + 5.2); vib.stop(t + 5.2);
  }

  // one deep, slow piano-like hit that rings out in the hall
  function lowHit(t, name, gain) {
    note(musicIn, 'triangle', hz(name), t, 4, gain);
    note(musicIn, 'sine', hz(name) * 2, t, 3, gain * 0.5);
    note(musicIn, 'sine', hz(name) * 3.01, t, 1.5, gain * 0.15);
    note(musicIn, 'sine', 95, t, 0.35, gain, 38);          // the thud
  }

  // one heartbeat thump (strong "lub" or softer "dub") - close, no echo
  function thump(t, strength) {
    note(musicBus, 'sine', 120, t, 0.24, 0.75 * strength, 42);
    note(musicBus, 'triangle', 200, t, 0.1, 0.2 * strength, 80);   // audible on phone speakers
  }

  // schedule everything that happens on one half-beat step (8 steps = 1 bar)
  function playStep(i, t, stepDur) {
    const bar = Math.floor(i / 8) % 16;            // 0..15
    const inBar = i % 8;
    const barDur = stepDur * 8;

    if (inBar === 0 && bar < 15) {
      // deep drone under everything; it gets more "wrong" as the loop goes on
      drone(hz('D2'), t, barDur, 0.2, 'sine');
      drone(hz('D3'), t, barDur, 0.07, 'triangle');
      if (bar >= 8)  drone(hz('D#3'), t, barDur, 0.045, 'triangle');   // clashing neighbour note
      if (bar >= 12) drone(hz('G#2'), t, barDur, 0.08, 'triangle');    // the "devil's interval"
    }

    // deep hits that mark each section
    if (inBar === 0 && (bar === 0 || bar === 8)) lowHit(t, 'D2', 0.5);
    if (inBar === 0 && bar === 4) lowHit(t, 'A#1', 0.45);
    if (inBar === 0 && bar === 12) lowHit(t, 'G#1', 0.5);
    if (inBar === 4 && bar === 15) lowHit(t, 'D2', 0.6);                // after the silence

    // broken music box (louder and frantic at the end)
    MUSIC_BOX[bar].forEach(function (n) {
      if (n[0] === inBar) musicBox(hz(n[1]), t, bar >= 12 ? 0.15 : 0.2);
    });

    // string clusters that grow and then cut off dead
    if (inBar === 0 && bar === 6)  stringSwell(['D4', 'D#4', 'G#4', 'A4'], t, barDur * 2 - 0.3, 0.07);
    if (inBar === 0 && bar === 13) stringSwell(['A4', 'A#4', 'E5', 'F5', 'B5'], t, barDur * 2 - 0.3, 0.075);
    if (inBar === 0 && bar === 14) screech(t, barDur - 0.3);

    // breaths and ghost voices in the empty spaces
    if (inBar === 4 && bar === 1)  wail(t, 'A5', 'G#5');
    if (inBar === 0 && bar === 3)  breath(t, 5);
    if (inBar === 0 && bar === 5)  wail(t, 'F5', 'E5');
    if (inBar === 4 && bar === 9)  breath(t, 6);
    if (inBar === 0 && bar === 11) wail(t, 'D6', 'C#6');

    // heartbeat: slow at first, twice as fast in the last section,
    // and it stops dead in the final bar
    if (bar < 12) {
      if (inBar === 0 || inBar === 4) { thump(t, 1); thump(t + 0.28, 0.6); }
    } else if (bar < 15) {
      if (inBar % 2 === 0) { thump(t, 1); thump(t + 0.22, 0.6); }
    }
  }

  // keeps the music scheduled a few seconds ahead (gap-free, works in OBS)
  function scheduleBeats() {
    if (!ctx || !musicOn || musicFileReady) return;
    buildMusicGraph();
    const stepDur = 60 / MUSIC_BPM / 2;
    if (nextStepTime < ctx.currentTime) nextStepTime = ctx.currentTime + 0.1;
    while (nextStepTime < ctx.currentTime + 3) {
      playStep(stepIndex, nextStepTime, stepDur);
      stepIndex++;
      nextStepTime += stepDur;
    }
  }

  // ======================= volume / on-off ================================
  function applyVolume() {
    const v = ducked ? Math.min(volume, MUSIC_DUCK_VOLUME) : volume;
    musicFile.volume = v;
    if (ctx) {
      // built-in music is only heard when no mysterious.mp3 is used
      const target = (musicOn && !musicFileReady) ? v * 2.4 : 0;
      musicBus.gain.setTargetAtTime(target, ctx.currentTime, 0.15);
    }
  }

  function musicIsPlaying() {
    if (!musicOn) return false;
    if (musicFileReady) return !musicFile.paused;
    return !!ctx && ctx.state === 'running';
  }

  function updateButton() {
    const btn = document.getElementById('music-btn');
    if (!btn) return;
    btn.textContent = musicOn ? (musicIsPlaying() ? '🔊 Music: ON' : '🔇 Music: ON (click page to start)') : '🔇 Music: OFF';
  }

  // Start (or resume) the music. Quietly does nothing if the browser blocks it.
  function startMusic() {
    if (!musicOn) { applyVolume(); updateButton(); return; }
    if (musicFileReady) {
      applyVolume();
      const p = musicFile.play();
      if (p && p.then) p.then(updateButton).catch(updateButton);
      return;
    }
    if (!audio()) return;
    const go = function () {
      applyVolume();
      scheduleBeats();
      clearInterval(beatTimer);
      beatTimer = setInterval(scheduleBeats, 500);
      updateButton();
    };
    if (ctx.state === 'running') go();
    else ctx.resume().then(go).catch(updateButton);
    updateButton();
  }

  function toggleMusic() {
    musicOn = !musicOn;
    try { localStorage.setItem('ctc-music-on', musicOn ? '1' : '0'); } catch (e) {}
    if (musicOn) startMusic();
    else { musicFile.pause(); applyVolume(); }
    updateButton();
  }

  function setMusic(on) { if (!!on !== musicOn) toggleMusic(); }
  function setSfx(on) {
    sfxOn = !!on;
    try { localStorage.setItem('ctc-sfx-on', sfxOn ? '1' : '0'); } catch (e) {}
  }

  function setVolume(v) {
    volume = Math.max(0, Math.min(1, v));
    try { localStorage.setItem('ctc-music-volume', String(volume)); } catch (e) {}
    applyVolume();
  }

  // ======================= sound effects ==================================
  // Plays your mp3 if it exists, otherwise the built-in sound.
  function play(name) {
    if (!sfxOn) return null;
    if (fileReady[name]) {
      try {
        const a = sfxFile[name].cloneNode();
        a.volume = SFX_VOLUME;
        const p = a.play();
        if (p && p.catch) p.catch(function () {});
        return a;
      } catch (e) { return null; }
    }
    if (synthSfx[name] && audio() && ctx.state === 'running') synthSfx[name](ctx.currentTime + 0.01);
    return null;
  }

  // Winner: keep the music playing but lower it to 10%, play the win sound
  // on top, then bring the music back.
  function playWin(maxMs) {
    ducked = true;
    applyVolume();
    const a = play('win');
    const restore = function () {
      clearTimeout(duckTimer);
      ducked = false;
      applyVolume();
    };
    clearTimeout(duckTimer);
    duckTimer = setTimeout(restore, a ? (maxMs || 8000) : 3200);
    if (a) a.addEventListener('ended', restore);
  }

  // ======================= start-up =======================================
  function init() {
    const btn = document.getElementById('music-btn');
    const slider = document.getElementById('music-volume');
    if (slider) {
      slider.value = Math.round(volume * 100);
      slider.addEventListener('input', function () { setVolume(slider.value / 100); });
    }
    if (btn) btn.addEventListener('click', toggleMusic);

    // Use sounds/mysterious.mp3 if it exists, otherwise the built-in music.
    musicFile.addEventListener('canplaythrough', function () {
      if (musicFileReady) return;
      musicFileReady = true;
      startMusic();
    });
    musicFile.addEventListener('error', function () { musicFileReady = false; });
    musicFile.src = SOUND_FOLDER + MUSIC_FILE;

    // 1) try to start straight away (works in OBS / TikTok Live Studio)
    startMusic();

    // 2) if the browser blocked sound, start on the first click / key press
    const unlock = function () {
      if (ctx && ctx.state !== 'running') ctx.resume();
      if (musicOn && !musicIsPlaying()) startMusic();
    };
    document.addEventListener('pointerdown', unlock);
    document.addEventListener('keydown', unlock);

    // key-press sound on every button
    document.addEventListener('click', function (e) {
      if (e.target.closest && e.target.closest('button')) play('click');
    });

    updateButton();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();

  return {
    play: play, playWin: playWin, startMusic: startMusic, toggleMusic: toggleMusic, setVolume: setVolume,
    setMusic: setMusic, setSfx: setSfx,
    musicOn: function () { return musicOn; }, sfxOn: function () { return sfxOn; },
    // for testing: the audio engine, so its output level can be measured
    // testing only: run every step of the tune once (call with music OFF = silent)
    _dryRun: function () { buildMusicGraph(); for (let i = 0; i < 128; i++) playStep(i, ctx.currentTime + 0.5, 0.5); return true; },
    _debug: function () { return { ctx: ctx, musicBus: musicBus, sfxBus: sfxBus, musicOn: musicOn, usingFile: musicFileReady }; }
  };
})();
